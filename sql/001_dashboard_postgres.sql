ALTER TABLE alerts ADD COLUMN IF NOT EXISTS notify_status TEXT NOT NULL DEFAULT 'pending';
ALTER TABLE alerts ADD COLUMN IF NOT EXISTS notify_detail TEXT;
ALTER TABLE notification_outbox ADD COLUMN IF NOT EXISTS provider_message_id TEXT;
ALTER TABLE notification_outbox ADD COLUMN IF NOT EXISTS reason_code TEXT;
ALTER TABLE notification_outbox ADD COLUMN IF NOT EXISTS completed_at TEXT;
