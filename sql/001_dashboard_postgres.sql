BEGIN;
CREATE SCHEMA IF NOT EXISTS avenra;
REVOKE ALL ON SCHEMA avenra FROM PUBLIC, anon, authenticated;
SET LOCAL search_path TO avenra, pg_catalog;



CREATE TABLE IF NOT EXISTS shelters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            TEXT    NOT NULL UNIQUE,
    lat             DOUBLE PRECISION,
    lng             DOUBLE PRECISION,
    beds_total      INTEGER NOT NULL DEFAULT 0,
    beds_available  INTEGER NOT NULL DEFAULT 0,
    accepting       INTEGER NOT NULL DEFAULT 1,
    languages       TEXT,
    hours           TEXT,
    walk_ins        INTEGER NOT NULL DEFAULT 0,
    verified        INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           TEXT NOT NULL,
    role           TEXT NOT NULL CHECK (role IN ('survivor','responder','shelter','admin')),
    email          TEXT NOT NULL UNIQUE,
    password_hash  TEXT,
    org            TEXT,
    case_code      TEXT UNIQUE,
    shelter_id     INTEGER REFERENCES shelters(id),
    is_active      INTEGER NOT NULL DEFAULT 0 CHECK(is_active IN (0,1)),
    auth_version   INTEGER NOT NULL DEFAULT 1 CHECK(auth_version>=1)
);

CREATE TABLE IF NOT EXISTS contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  INTEGER NOT NULL REFERENCES users(id),
    name     TEXT NOT NULL,
    phone    TEXT NOT NULL,
    UNIQUE (user_id, name)
);

CREATE TABLE IF NOT EXISTS alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          INTEGER NOT NULL REFERENCES users(id),
    case_code        TEXT NOT NULL,
    lat              DOUBLE PRECISION,
    lng              DOUBLE PRECISION,
    location_accuracy DOUBLE PRECISION,
    location_recorded_at TEXT,
    status           TEXT NOT NULL DEFAULT 'new'
                     CHECK (status IN ('new','acknowledged','in_progress','resolved')),
    acknowledged_by  TEXT,
    acknowledged_at  TEXT,
    client_id        TEXT UNIQUE,
    client_ts        TEXT,
    created_at       TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE TABLE IF NOT EXISTS referrals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id        INTEGER NOT NULL REFERENCES alerts(id),
    shelter_id      INTEGER NOT NULL REFERENCES shelters(id),
    status          TEXT NOT NULL DEFAULT 'sent'
                    CHECK (status IN ('sent','accepted','declined','placed')),
    decline_reason  TEXT,
    created_at      TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
    updated_at      TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);

CREATE TABLE IF NOT EXISTS diary_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER NOT NULL REFERENCES users(id),
    note              TEXT,
    photo_path        TEXT,
    file_hash         TEXT,
    note_sha256       TEXT,
    photo_sha256      TEXT,
    entry_fingerprint TEXT,
    contract_version  INTEGER NOT NULL DEFAULT 1,
    shared            INTEGER NOT NULL DEFAULT 0,
    client_id         TEXT UNIQUE,
    captured_at       TEXT,
    received_at       TEXT,
    created_at        TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);
CREATE INDEX IF NOT EXISTS idx_diary_user_client ON diary_entries(user_id, client_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_diary_user_client ON diary_entries(user_id, client_id) WHERE client_id IS NOT NULL;


CREATE TABLE IF NOT EXISTS consents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER NOT NULL REFERENCES users(id),
    item        TEXT NOT NULL,
    granted_to  TEXT NOT NULL,
    granted_at  TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
    revoked_at  TEXT
);

CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts         TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
    actor      TEXT NOT NULL,
    action     TEXT NOT NULL,
    case_code  TEXT,
    detail     TEXT
);

CREATE INDEX IF NOT EXISTS idx_alerts_created ON alerts(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_ts       ON audit_log(ts DESC);



CREATE TABLE IF NOT EXISTS case_access (
    staff_id INTEGER NOT NULL REFERENCES users(id),
    survivor_id INTEGER NOT NULL REFERENCES users(id),
    PRIMARY KEY (staff_id, survivor_id)
);
CREATE TABLE IF NOT EXISTS alert_workflow (
    alert_id INTEGER PRIMARY KEY REFERENCES alerts(id),
    assigned_to INTEGER REFERENCES users(id),
    escalated_at TEXT,
    revision INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS alert_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id INTEGER NOT NULL REFERENCES alerts(id),
    actor_id INTEGER REFERENCES users(id),
    action TEXT NOT NULL,
    detail TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);
CREATE INDEX IF NOT EXISTS idx_alert_history ON alert_history(alert_id, id);

CREATE TABLE IF NOT EXISTS notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id INTEGER NOT NULL REFERENCES alerts(id) ON DELETE CASCADE,
    contact_id INTEGER NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN (
            'pending', 'processing', 'accepted', 'delivered',
            'failed', 'unknown', 'cancelled'
        )),
    claim_token TEXT,
    claimed_at TEXT,
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
    UNIQUE (alert_id, contact_id)
);

CREATE INDEX IF NOT EXISTS idx_notification_outbox_pending
    ON notification_outbox(status, id);


CREATE TABLE IF NOT EXISTS notification_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id INTEGER NOT NULL REFERENCES alerts(id) ON DELETE CASCADE,
    contact_id INTEGER NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN (
        'pending','processing','accepted','delivered','failed','unknown','cancelled')),
    claim_token TEXT,
    claimed_at TEXT,
    provider_message_id TEXT,
    reason_code TEXT,
    completed_at TEXT,
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
    UNIQUE(alert_id,contact_id)
);
CREATE INDEX IF NOT EXISTS idx_notification_outbox_pending ON notification_outbox(status,id);
CREATE TABLE IF NOT EXISTS notification_batches (
    alert_id INTEGER PRIMARY KEY REFERENCES alerts(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id),
    attempted_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))
);
CREATE INDEX IF NOT EXISTS idx_notification_batches_user ON notification_batches(user_id,attempted_at);
;
CREATE TABLE IF NOT EXISTS push_invites (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,contact_id INTEGER NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
 token_hash TEXT UNIQUE NOT NULL,expires_at TEXT NOT NULL,used_at TEXT,
 created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')));
CREATE INDEX IF NOT EXISTS push_invite_contact ON push_invites(contact_id);
CREATE TABLE IF NOT EXISTS push_subscriptions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,contact_id INTEGER NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
 endpoint_hash TEXT NOT NULL,encrypted_subscription TEXT NOT NULL,browser_hash TEXT NOT NULL,
 active INTEGER NOT NULL DEFAULT 1 CHECK(active IN(0,1)),last_test_at TEXT,
 created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')),
 UNIQUE(contact_id,endpoint_hash));
CREATE TABLE IF NOT EXISTS push_acknowledgements (
 job_id INTEGER PRIMARY KEY REFERENCES notification_outbox(id) ON DELETE CASCADE,
 subscription_id INTEGER NOT NULL REFERENCES push_subscriptions(id) ON DELETE CASCADE,
 token_hash TEXT NOT NULL UNIQUE,expires_at TEXT NOT NULL,acknowledged_at TEXT);
;CREATE TABLE IF NOT EXISTS staff_invitations (
